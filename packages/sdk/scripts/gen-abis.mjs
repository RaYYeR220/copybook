// Regenerates src/abi/*.ts from the forge artifacts in contracts/out (run `forge build` in contracts/ first).
// The output is committed, so consumers (the app, the MCP server) never need forge.
import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "../../..");
const outDir = resolve(dirname(fileURLToPath(import.meta.url)), "../src/abi");

function abiOf(file, name) {
  const path = resolve(root, `contracts/out/${file}/${name}.json`);
  if (!existsSync(path)) throw new Error(`missing ${path}: run forge build in contracts/`);
  return JSON.parse(readFileSync(path, "utf8")).abi;
}

const sig = (x) => `${x.type}:${x.name ?? ""}(${(x.inputs ?? []).map((i) => i.type).join(",")})`;
const dedupe = (items) => [...new Map(items.map((x) => [sig(x), x])).values()];
const errorsOf = (abi) => abi.filter((x) => x.type === "error");

const hub = abiOf("CopybookHub.sol", "CopybookHub");
const themes = abiOf("ThemeRegistry.sol", "ThemeRegistry");
const gate = abiOf("RiskGate.sol", "RiskGate");
// Reverts the hub surfaces from the linked engine and policy library, for decoding failed writes.
const engineErrors = dedupe([
  ...errorsOf(abiOf("CopyEngine.sol", "CopyEngine")),
  ...errorsOf(abiOf("PolicyLib.sol", "PolicyLib")),
]);

const header = "// Generated by scripts/gen-abis.mjs from contracts/out. Do not edit by hand.\n";
const emit = (file, name, abi) =>
  writeFileSync(resolve(outDir, file), `${header}export const ${name} = ${JSON.stringify(abi, null, 2)} as const;\n`);

mkdirSync(outDir, { recursive: true });
emit("hub.ts", "hubAbi", hub);
emit("themes.ts", "themesAbi", themes);
emit("gate.ts", "gateAbi", gate);
emit("engineErrors.ts", "engineErrorsAbi", engineErrors);
console.log(`wrote ABIs: hub ${hub.length}, themes ${themes.length}, gate ${gate.length}, engine errors ${engineErrors.length}`);
